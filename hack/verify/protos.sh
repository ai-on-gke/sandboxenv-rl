# Regenerates Go and Python protobuf stubs in an isolated temporary copy
# and verifies stubs against proto sources without modifying the working tree.
#
# What it does:
#   1. Resolves repository root and sets up environment.
#   2. Detects a Python interpreter containing the grpcio-tools package.
#   3. Copies the working tree (tracked + untracked unignored files) into an
#      isolated temporary directory.
#   4. Regenerates Python protobuf and gRPC stubs via `make python-protos` inside
#      the temporary copy.
#   5. Regenerates Go protobuf and gRPC stubs using `go tool buf generate` inside
#      the temporary copy.
#   6. Compares the temporary copy's stub directories against the working tree stubs
#      via recursive diff (`diff -r`), ignoring generator headers.
#   7. Cleans up the temporary directory on exit; never modifies the working tree.
#
# When it runs:
#   - CI: Executed as part of the `go` job (`ci-go`) in .github/workflows/ci.yaml.
#   - Wrapped by `make verify-protos` (host-level) and `make ci-go`.
#
# How to run:
#   - `make verify-protos` (host-level verification)
#   - `make protos` (regenerates stubs via Nix or Docker)
#   - `make ci-go` (runs build, vet, test -race, format, docs, and verify-protos)
#   - Direct: `./hack/verify/protos.sh [DIFF_TARGETS...]`
#   Examples:
#     make verify-protos
#     make protos
#     make ci-go
#     ./hack/verify/protos.sh
#
# Prerequisites:
#   - Go toolchain (go.mod pins buf, protoc-gen-go, and protoc-gen-go-grpc via tool directives).
#   - Python 3 with `grpcio-tools` installed (in the devShell's Python env, built from uv.lock).
#     Note: the Python stub generator (grpcio-tools) is pinned in clients/python/pyproject.toml
#     and uv.lock.
#
# Environment variables:
#   PYTHON  python3  Python interpreter to use for generating Python stubs (must have grpcio-tools)
#
# Outputs / exit codes:
#   - The working tree is never modified.
#   - Exits with 0 if all stubs match .proto definitions cleanly.
#   - Exits with 1 if stubs are out-of-date, missing, or extra files are generated.
#
# Troubleshooting:
#   - Stub drift / CI failure: Run `make protos` locally (or inside `nix develop`) and
#     commit any updated Go or Python stubs.
#   - Missing generator dependencies: Use `make protos` (which auto-selects Nix or Docker) rather
#     than direct host execution if grpcio-tools is missing from the host.
#
# See also:
#   proto/, go.mod, clients/python/scripts/gen-protos.sh, Makefile, nix/ci.nix.

set -o errexit -o nounset -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
cd "${REPO_ROOT}"

# Detect Python interpreter with grpcio-tools
if [[ -z "${PYTHON:-}" ]]; then
  if python3 -c 'import grpc_tools' >/dev/null 2>&1; then
    export PYTHON="python3"
  elif [[ -x "${REPO_ROOT}/.venv/bin/python" ]] && "${REPO_ROOT}/.venv/bin/python" -c 'import grpc_tools' >/dev/null 2>&1; then
    export PYTHON="${REPO_ROOT}/.venv/bin/python"
  else
    export PYTHON="python3"
  fi
fi

DIFF_TARGETS=("proto/" "clients/python/src/ate_env/_gen/")
if [[ $# -gt 0 ]]; then
  DIFF_TARGETS=("$@")
fi

TMP_DIR="$(mktemp -d)"
# shellcheck disable=SC2329 # invoked indirectly via trap
cleanup() {
  rm -rf "${TMP_DIR}"
}
trap cleanup EXIT

# Copy working tree (tracked + untracked unignored files) into isolated temporary directory.
git ls-files -co --exclude-standard -z | tar --null --ignore-failed-read -T - -cf - | tar -C "${TMP_DIR}" -xf -

# Regenerate Python protobuf stubs inside temp directory
echo "Regenerating Python protobuf stubs..."
(cd "${TMP_DIR}" && make python-protos)

# Regenerate Go protobuf stubs inside temp directory
echo "Regenerating Go protobuf stubs..."
(cd "${TMP_DIR}" && go tool buf generate)

# Ensure generated stubs match .proto files
echo "Verifying generated stubs match .proto files..."

DIFF_OPTS=(
  -I '^//[[:space:]]*protoc'
  -I '^//[[:space:]]*protoc-gen-go'
  -I '^//[[:space:]]*protoc-gen-go-grpc'
  -I '^# -\*- coding'
  -I '^# Generated by'
  -x '__pycache__'
  -x '*.pyc'
)

FIX_HINT="To fix: run \`make protos\` (regenerates the Go and Python stubs with the
pinned toolchains), then commit the changes under proto/ and
clients/python/src/ate_env/_gen/."

diff_failed=0
for target in "${DIFF_TARGETS[@]}"; do
  clean_target="${target%/}"
  if ! diff -r -u "${DIFF_OPTS[@]}" "${clean_target}" "${TMP_DIR}/${clean_target}"; then
    diff_failed=1
  fi
done

if [[ ${diff_failed} -ne 0 ]]; then
  echo "Error: generated protobuf stubs do not match .proto sources." >&2
  echo "${FIX_HINT}" >&2
  exit 1
fi

echo "Protobuf stub verification passed."
